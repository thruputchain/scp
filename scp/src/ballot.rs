use std::cmp::Ordering;
use std::collections::{HashMap, HashSet};
use std::mem::discriminant;
use tracing::{debug, error, instrument, trace};

#[derive(Debug)]
pub struct BallotState {
    heard_from_quorum: bool,

    current: Option<proto::SCPBallot>,        // b
    prepared: Option<proto::SCPBallot>,       // p
    prepared_prime: Option<proto::SCPBallot>, // p'
    high: Option<proto::SCPBallot>,           // h
    commit: Option<proto::SCPBallot>,         // c
    value_override: Option<proto::SCPValue>,  // z
    latest_envelopes: HashMap<proto::SCPNodeID, proto::SCPEnvelope>, // M
    phase: Phase,                             // phi

    msg_level: i64,       // number of messages triggered in one run
    timer_exp_count: i64, // number of times the timer has expired; used for the quorum endpoint

    last_envelope_gen: Option<proto::SCPEnvelope>, // last envelope generated by this node
    last_envelope_emit: Option<proto::SCPEnvelope>, // last envelope emitted by this node
}

impl BallotState {
    pub fn new() -> Self {
        BallotState {
            heard_from_quorum: false,
            current: None,
            prepared: None,
            prepared_prime: None,
            high: None,
            commit: None,
            value_override: None,
            latest_envelopes: HashMap::new(),
            phase: Phase::Prepare,
            msg_level: 0,
            timer_exp_count: 0,
            last_envelope_gen: None,
            last_envelope_emit: None,
        }
    }
}

#[derive(Debug)]
pub struct BallotProto<'a, 'b>(pub &'a mut SlotProto<'b>);

impl<'a, 'b> BallotProto<'a, 'b> {
    fn slot_proto_mut(&mut self) -> &mut SlotProto<'b> {
        self.0
    }

    fn slot_proto(&self) -> &SlotProto<'b> {
        self.0
    }

    fn ballot_state(&self) -> &BallotState {
        self.slot_proto().ballot_state()
    }

    fn ballot_state_mut(&mut self) -> &mut BallotState {
        self.slot_proto_mut().ballot_state_mut()
    }

    fn driver(&self) -> &dyn Driver {
        self.slot_proto().driver()
    }

    fn consensus(&self) -> &dyn Consensus {
        self.slot_proto().consensus()
    }

    // proto

    fn record_envelope(&mut self, env: &proto::SCPEnvelope) {
        let node_id = env.statement.node_id.clone();
        self.ballot_state_mut()
            .latest_envelopes
            .insert(node_id, env.clone());
        self.slot_proto_mut().record_statement(&env.statement);
    }

    pub fn is_newer_node_statement(
        &self,
        node_id: &proto::SCPNodeID,
        st: &proto::SCPStatement,
    ) -> bool {
        match self.ballot_state().latest_envelopes.get(node_id) {
            Some(old) => Self::is_newer_statement(&old.statement, st),
            None => true,
        }
    }

    pub fn is_newer_statement(older: &proto::SCPStatement, newer: &proto::SCPStatement) -> bool {
        if discriminant(&older.pledges) != discriminant(&newer.pledges) {
            older.pledges.stmt_type() < newer.pledges.stmt_type()
        } else if newer.pledges.stmt_type() == proto::SCPStatementType::SCP_ST_EXTERNALIZE as i32 {
            false
        } else {
            match (&older.pledges, &newer.pledges) {
                // both confirm
                (
                    proto::SCPStatement_pledges::SCP_ST_CONFIRM {
                        confirm: older_confirm,
                    },
                    proto::SCPStatement_pledges::SCP_ST_CONFIRM {
                        confirm: newer_confirm,
                    },
                ) => match compare_ballots(&older_confirm.ballot, &newer_confirm.ballot) {
                    Ordering::Less => true,
                    Ordering::Equal => {
                        if older_confirm.n_prepared == newer_confirm.n_prepared {
                            older_confirm.n_h < newer_confirm.n_h
                        } else {
                            older_confirm.n_prepared < newer_confirm.n_prepared
                        }
                    }
                    Ordering::Greater => false,
                },
                // both prepare
                (
                    proto::SCPStatement_pledges::SCP_ST_PREPARE {
                        prepare: older_prepare,
                    },
                    proto::SCPStatement_pledges::SCP_ST_PREPARE {
                        prepare: newer_prepare,
                    },
                ) => match compare_ballots(&older_prepare.ballot, &newer_prepare.ballot) {
                    Ordering::Less => true,
                    Ordering::Equal => {
                        match compare_opt_ballots(&older_prepare.prepared, &newer_prepare.prepared)
                        {
                            Ordering::Less => true,
                            Ordering::Equal => match compare_opt_ballots(
                                &older_prepare.prepared_prime,
                                &newer_prepare.prepared_prime,
                            ) {
                                Ordering::Less => true,
                                Ordering::Equal => older_prepare.n_h < newer_prepare.n_h,
                                Ordering::Greater => false,
                            },
                            Ordering::Greater => false,
                        }
                    }
                    Ordering::Greater => false,
                },
                // unreachable
                _ => panic!(),
            }
        }
    }

    pub fn get_statement_values(st: &proto::SCPStatement) -> HashSet<proto::SCPValue> {
        let mut values = HashSet::new();

        match &st.pledges {
            proto::SCPStatement_pledges::SCP_ST_PREPARE { prepare } => {
                let b = &prepare.ballot;
                if b.counter != 0 {
                    values.insert(prepare.ballot.value.clone());
                }
                if let Some(prepared) = &prepare.prepared {
                    values.insert(prepared.value.clone());
                }
                if let Some(prepared_prime) = &prepare.prepared_prime {
                    values.insert(prepared_prime.value.clone());
                }
            }
            proto::SCPStatement_pledges::SCP_ST_CONFIRM { confirm } => {
                values.insert(confirm.ballot.value.clone());
            }
            proto::SCPStatement_pledges::SCP_ST_EXTERNALIZE { externalize } => {
                values.insert(externalize.commit.value.clone());
            }
            _ => panic!("bug"),
        }

        values
    }

    #[instrument]
    pub fn process_envelope(&mut self, env: &proto::SCPEnvelope, ours: bool) -> EnvelopeState {
        assert!(env.statement.slot_index == self.slot_proto().index());

        let statement = &env.statement;

        fn check_valid<'a, 'b>(
            ballot_proto: &mut BallotProto<'a, 'b>,
            statement: &proto::SCPStatement,
            ours: bool,
            env: &proto::SCPEnvelope,
        ) -> EnvelopeState {
            if ballot_proto.is_statement_sane(statement, ours) {
                if ours {
                    error!(env = ?env, "not sane statement from self, skipping");
                }
                return EnvelopeState::Invalid;
            }
            if !ballot_proto.is_newer_node_statement(&statement.node_id, statement) {
                if ours {
                    error!(env = ?env, "stale statement from self, skipping")
                } else {
                    trace!(
                        slot_index = ballot_proto.slot_proto().index(),
                        "stale statement, skipping"
                    )
                }
                return EnvelopeState::Invalid;
            }
            EnvelopeState::Valid
        }

        if let EnvelopeState::Invalid = check_valid(self, statement, ours, env) {
            return EnvelopeState::Invalid;
        }

        let validation_result = self.validate_values(statement); //XXX: must be async
        match validation_result {
            ValidationLevel::Invalid => {
                if ours {
                    error!(env = ?env, "invalid value from self, skipping")
                } else {
                    trace!(slot_index = self.slot_proto().index(), "invalid value")
                }
                return EnvelopeState::Invalid;
            }
            _ => {}
        }

        // check if validity has changed since the call into the app
        if let EnvelopeState::Invalid = check_valid(self, statement, ours, env) {
            return EnvelopeState::Invalid;
        }

        if !matches!(self.ballot_state().phase, Phase::Externalize) {
            if let ValidationLevel::MaybeValid = validation_result {
                self.slot_proto_mut().set_fully_validated(false);
            }
            self.record_envelope(env);
            self.advance_slot(statement); //XXX:async?
            return EnvelopeState::Valid;
        }

        // this handles also our own messages
        // in particular our final EXTERNALIZE message
        match &self.ballot_state().commit {
            Some(c) => {
                if c.value == Self::get_working_ballot(statement).value {
                    self.record_envelope(env);
                    return EnvelopeState::Valid;
                }
            }
            _ => assert!(false),
        }

        if ours {
            error!(env = ?env, "externalize statement with invalid value from self, skipping");
        }

        return EnvelopeState::Invalid;
    }

    pub fn is_statement_sane(&self, statement: &proto::SCPStatement, ours: bool) -> bool {
        match &self.slot_proto().get_quorum_set_from_statement(statement) {
            Some(qset) => {
                if let Result::Err(e) = is_qset_sane(qset, false) {
                    debug!(err = ?e, "invalid quorum set received");
                    return false;
                }
            }
            None => {
                debug!(statement = ?statement, "unknown quorum set");
                return false;
            }
        }

        match &statement.pledges {
            proto::SCPStatement_pledges::SCP_ST_PREPARE { prepare } => {
                // self is allowed to have b = 0 (as long as it never gets emitted)
                if !(ours || prepare.ballot.counter > 0) {
                    trace!(statement = ?statement, "malformed PREPARE message");
                    return false;
                }
                match (&prepare.prepared_prime, &prepare.prepared) {
                    (Some(pp), Some(p)) => {
                        if !are_ballots_less_and_incompatible(pp, p) {
                            trace!(statement = ?statement, "malformed PREPARE message");
                            return false;
                        }
                    }
                    _ => {}
                }
                if prepare.n_h != 0 {
                    match &prepare.prepared {
                        Some(p) => {
                            if prepare.n_h > p.counter {
                                trace!(statement = ?statement, "malformed PREPARE message");
                                return false;
                            }
                        }
                        _ => {
                            trace!(statement = ?statement, "malformed PREPARE message");
                            return false;
                        }
                    }
                }
                // c != 0 -> c <= h <= b
                if prepare.n_c != 0 {
                    if !(prepare.n_h != 0
                        && prepare.ballot.counter >= prepare.n_h
                        && prepare.n_h >= prepare.n_c)
                    {
                        trace!(statement = ?statement, "malformed PREPARE message");
                        return false;
                    }
                }
                return true;
            }
            proto::SCPStatement_pledges::SCP_ST_CONFIRM { confirm } => {
                // c <= h <= b
                if confirm.ballot.counter <= 0 {
                    trace!(statement = ?statement, "malformed CONFIRM message");
                    return false;
                }
                if confirm.n_h > confirm.ballot.counter {
                    trace!(statement = ?statement, "malformed CONFIRM message");
                    return false;
                }
                if confirm.n_commit > confirm.n_h {
                    trace!(statement = ?statement, "malformed CONFIRM message");
                    return false;
                }
                return true;
            }
            proto::SCPStatement_pledges::SCP_ST_EXTERNALIZE { externalize } => {
                if externalize.commit.counter <= 0 {
                    trace!(statement = ?statement, "malformed EXTERNALIZE message");
                    return false;
                }
                if externalize.n_h < externalize.commit.counter {
                    trace!(statement = ?statement, "malformed EXTERNALIZE message");
                    return false;
                }
                return true;
            }
            proto::SCPStatement_pledges::SCP_ST_NOMINATE { nominate: _ } => {
                panic!("unreachable");
            }
        }
    }

    #[instrument]
    fn abandon_ballot(&mut self, n: u32) -> bool {
        trace!("abandoning ballot");
        let v = match self.slot_proto_mut().get_latest_composite_candidate() {
            Some(w) => {
                if w.is_empty() {
                    match &self.ballot_state().current {
                        Some(cv) => Some(cv.value.clone()),
                        None => None,
                    }
                } else {
                    Some(w.clone())
                }
            }
            None => match &self.ballot_state().current {
                Some(cv) => Some(cv.value.clone()),
                None => None,
            },
        };
        match v {
            Some(w) => {
                if w.is_empty() {
                    return false;
                } else {
                    if n == 0 {
                        return self.bump_state(w, true);
                    } else {
                        return self.bump_state_n(w, n);
                    }
                }
            }
            None => {
                return false;
            }
        }
    }

    #[instrument]
    fn bump_state(&mut self, value: proto::SCPValue, force: bool) -> bool {
        let n = match &self.ballot_state().current {
            Some(b) => {
                if !force {
                    return false;
                }
                b.counter + 1
            }
            None => 1,
        };
        self.bump_state_n(value, n)
    }

    fn bump_state_n(&mut self, value: proto::SCPValue, n: u32) -> bool {
        return match self.ballot_state().phase {
            Phase::Prepare | Phase::Confirm => {
                let newv = match &self.ballot_state().value_override {
                    Some(v) => v.clone(),
                    None => value,
                };
                let newb = proto::SCPBallot {
                    counter: n,
                    value: newv,
                };
                trace!(
                    slot_index = self.slot_proto().index(),
                    ballot = ?newb,
                    "ballot protocol bump state"
                );
                let updated = self.update_current_value(newb);
                if updated {
                    self.emit_current_state_statement();
                    self.check_heard_from_quorum();
                };
                updated
            }
            Phase::Externalize | Phase::Num => false,
        };
    }

    /// updates the local state based to the specified ballot
    /// (that could be a prepared ballot) enforcing invariants
    #[instrument]
    fn update_current_value(&mut self, new_ballot: proto::SCPBallot) -> bool {
        if self.ballot_state().phase != Phase::Prepare
            && self.ballot_state().phase != Phase::Confirm
        {
            return false;
        };
        let updated = match &self.ballot_state().current {
            None => {
                self.bump_to_ballot(new_ballot, true);
                true
            }
            Some(current) => {
                assert!(compare_ballots(current, &new_ballot) != Ordering::Greater);
                if let Some(commit) = &self.ballot_state().commit {
                    if !are_ballots_compatible(commit, &new_ballot) {
                        return false;
                    }
                }
                match compare_ballots(current, &new_ballot) {
                    Ordering::Less => {
                        self.bump_to_ballot(new_ballot, true);
                        true
                    }
                    Ordering::Equal => false,
                    Ordering::Greater => {
                        // this code probably changes with the final version
                        // of the conciliator
                        // this case may happen if the other nodes are not
                        // following the protocol (and we end up with a smaller value)
                        // not sure what is the best way to deal
                        // with this situation
                        error!(
                            "ballot protocol update_current_value attempt to bump to a smaller value"
                        );
                        // can't just bump to the value as we may already have
                        // statements at counter+1
                        return false;
                    }
                }
            }
        };
        self.check_invariants();
        updated
    }

    #[instrument(fields(slot_index=self.slot_proto().index(), ballot_counter=ballot.counter))]
    fn bump_to_ballot(&mut self, ballot: proto::SCPBallot, check: bool) {
        trace!(
            slot_index = self.slot_proto().index(),
            ballot = ?ballot,
            "ballot proto bump_to_ballot"
        );

        // `bump_to_ballot` should be never called once we committed
        assert!(self.ballot_state().phase != Phase::Externalize);

        if check {
            match &self.ballot_state().current {
                Some(current) => assert!(compare_ballots(&ballot, current) != Ordering::Less),
                None => {}
            }
        }

        let got_bumped = match &self.ballot_state().current {
            Some(current) => current.counter != ballot.counter,
            None => true,
        };

        match &self.ballot_state().current {
            None => {
                self.slot_proto()
                    .cd
                    .consensus
                    .started_ballot_proto(self.slot_proto().index(), &ballot);
            }
            Some(_) => {}
        }

        self.ballot_state_mut().current = Some(ballot);

        // we have to clear some fields (and recompute them based on latest
        // messages)
        // invariant: h.value = b.value
        if let Some(high) = &self.ballot_state().high {
            if !are_ballots_compatible(self.ballot_state().current.as_ref().unwrap(), high) {
                self.ballot_state_mut().high = None;
                // invariant: c set only when h is set
                self.ballot_state_mut().commit = None;
            }
        }

        if got_bumped {
            self.ballot_state_mut().heard_from_quorum = false;
        }
    }

    fn start_timer(&mut self) {
        let driver = &self.slot_proto().cd.driver;
        let timeout =
            driver.compute_timeout(self.ballot_state().current.as_ref().unwrap().counter, false);
        let slot_index = self.slot_proto().index();
        driver.start_timer(
            slot_index,
            Timer::Ballot,
            timeout,
            DriverCallback::BallotTimerExpired {
                slot_index: slot_index,
            },
        );
    }

    fn stop_timer(&mut self) {
        let driver = &self.slot_proto().cd.driver;
        driver.stop_timer(self.slot_proto().index(), Timer::Ballot);
    }

    pub fn driver_calling_back(&mut self, cb: DriverCallback) {
        match cb {
            DriverCallback::BallotTimerExpired { slot_index: _ } => self.timer_expired(),
            _ => {}
        }
    }

    pub fn timer_expired(&mut self) {
        self.ballot_state_mut().timer_exp_count += 1;
        self.abandon_ballot(0);
    }

    #[instrument]
    fn create_statement(&self, typ: proto::SCPStatementType) -> proto::SCPStatement {
        self.check_invariants();

        let pledges = match typ {
            proto::SCPStatementType::SCP_ST_PREPARE => {
                let mut prepare = proto::SCPStatementPrepare {
                    quorum_set_hash: self.slot_proto().local_proto().get_qset_hash().clone(),
                    ballot: proto::SCPBallot {
                        counter: 0,
                        value: Default::default(),
                    },
                    prepared: None,
                    prepared_prime: None,
                    n_c: 0,
                    n_h: 0,
                };

                if let Some(ref current) = self.ballot_state().current {
                    prepare.ballot = current.clone();
                }

                if let Some(ref commit) = self.ballot_state().commit {
                    prepare.n_c = commit.counter;
                }

                if let Some(ref prepared) = self.ballot_state().prepared {
                    prepare.prepared = Some(prepared.clone());
                }

                if let Some(ref prepared_prime) = self.ballot_state().prepared_prime {
                    prepare.prepared_prime = Some(prepared_prime.clone());
                }

                if let Some(ref high) = self.ballot_state().high {
                    prepare.n_h = high.counter;
                }

                proto::SCPStatement_pledges::SCP_ST_PREPARE { prepare }
            }

            proto::SCPStatementType::SCP_ST_CONFIRM => {
                let confirm = proto::SCPStatementConfirm {
                    ballot: self.ballot_state().current.as_ref().unwrap().clone(),
                    n_prepared: self.ballot_state().prepared.as_ref().unwrap().counter,
                    n_commit: self.ballot_state().commit.as_ref().unwrap().counter,
                    n_h: self.ballot_state().high.as_ref().unwrap().counter,
                    quorum_set_hash: self.slot_proto().local_proto().get_qset_hash().clone(),
                };

                proto::SCPStatement_pledges::SCP_ST_CONFIRM { confirm }
            }

            proto::SCPStatementType::SCP_ST_EXTERNALIZE => {
                let externalize = proto::SCPStatementExternalize {
                    commit: self.ballot_state().commit.as_ref().unwrap().clone(),
                    n_h: self.ballot_state().high.as_ref().unwrap().counter,
                    commit_quorum_set_hash: self.slot_proto().local_proto().get_qset_hash().clone(),
                };

                proto::SCPStatement_pledges::SCP_ST_EXTERNALIZE { externalize }
            }

            proto::SCPStatementType::SCP_ST_NOMINATE => {
                panic!("create_statement should not be called with SCP_ST_NOMINATE");
            }
        };

        proto::SCPStatement {
            node_id: self.slot_proto().local_proto().get_node_id().clone(),
            slot_index: self.slot_proto().index(),
            pledges,
        }
    }

    #[instrument]
    fn send_latest_envelope(&mut self) {
        // emit current envelope if needed
        if self.ballot_state().msg_level == 0 && self.slot_proto().is_fully_validated() {
            let driver = &self.slot_proto().cd.driver;
            let ballot_mut = self.ballot_state_mut();
            if let Some(last_gen) = &ballot_mut.last_envelope_gen {
                let should_emit = match &ballot_mut.last_envelope_emit {
                    None => true,
                    Some(last_emit) => last_gen != last_emit,
                };

                if should_emit {
                    ballot_mut.last_envelope_emit = Some(last_gen.clone());
                    driver.emit_envelope(last_gen.clone());
                }
            }
        }
    }

    #[instrument]
    fn emit_current_state_statement(&mut self) {
        let statement_type = match self.ballot_state().phase {
            Phase::Prepare => proto::SCPStatementType::SCP_ST_PREPARE,
            Phase::Confirm => proto::SCPStatementType::SCP_ST_CONFIRM,
            Phase::Externalize => proto::SCPStatementType::SCP_ST_EXTERNALIZE,
            Phase::Num => panic!("bug"),
        };

        let statement = self.create_statement(statement_type);
        let envelope = self.slot_proto().create_envelope(statement);

        let can_emit = self.ballot_state().current.is_some();

        // if we generate the same envelope, don't process it again
        // this can occur when updating h in PREPARE phase
        // as statements only keep track of h.n (but h.x could be different)
        let local_proto = self.slot_proto().local_proto();
        let local_node_id = local_proto.get_node_id();
        let last_env = self.ballot_state().latest_envelopes.get(local_node_id);

        let should_process = match last_env {
            None => true,
            Some(last_envelope) => last_envelope != &envelope,
        };

        if should_process {
            let envelope_state = self.process_envelope(&envelope, true);
            if envelope_state == EnvelopeState::Valid {
                let should_emit = can_emit && {
                    match &self.ballot_state().last_envelope_gen {
                        None => true,
                        Some(last_gen) => {
                            Self::is_newer_statement(&last_gen.statement, &envelope.statement)
                        }
                    }
                };

                if should_emit {
                    self.ballot_state_mut().last_envelope_gen = Some(envelope.clone());
                    // this will no-op if invoked from advanceSlot
                    // as advanceSlot consolidates all messages sent
                    self.send_latest_envelope();
                }
            } else {
                // there is a bug in the application if it queued up
                // a statement for itself that it considers invalid
                panic!("moved to a bad state (ballot protocol)");
            }
        }
    }

    #[instrument]
    fn get_prepare_candidates(&self, hint: &proto::SCPStatement) -> HashSet<proto::SCPBallot> {
        let mut hint_ballots = HashSet::new();

        match &hint.pledges {
            proto::SCPStatement_pledges::SCP_ST_PREPARE { prepare } => {
                hint_ballots.insert(prepare.ballot.clone());
                if let Some(ref prepared) = prepare.prepared {
                    hint_ballots.insert(prepared.clone());
                }
                if let Some(ref prepared_prime) = prepare.prepared_prime {
                    hint_ballots.insert(prepared_prime.clone());
                }
            }
            proto::SCPStatement_pledges::SCP_ST_CONFIRM { confirm } => {
                hint_ballots.insert(proto::SCPBallot {
                    counter: confirm.n_prepared,
                    value: confirm.ballot.value.clone(),
                });
                hint_ballots.insert(proto::SCPBallot {
                    counter: u32::MAX,
                    value: confirm.ballot.value.clone(),
                });
            }
            proto::SCPStatement_pledges::SCP_ST_EXTERNALIZE { externalize } => {
                hint_ballots.insert(proto::SCPBallot {
                    counter: u32::MAX,
                    value: externalize.commit.value.clone(),
                });
            }
            proto::SCPStatement_pledges::SCP_ST_NOMINATE { .. } => {
                panic!("getPrepareCandidates should not be called with SCP_ST_NOMINATE");
            }
        }

        let mut candidates = HashSet::new();

        // Process hint ballots from highest to lowest
        while !hint_ballots.is_empty() {
            // Find the highest ballot (by counter, then by value)
            let top_vote = hint_ballots
                .iter()
                .max_by(|a, b| compare_ballots(a, b))
                .unwrap()
                .clone();
            hint_ballots.remove(&top_vote);

            let val = &top_vote.value;

            // Find candidates that may have been prepared
            for envelope in self.ballot_state().latest_envelopes.values() {
                match &envelope.statement.pledges {
                    proto::SCPStatement_pledges::SCP_ST_PREPARE { prepare } => {
                        if are_ballots_less_and_compatible(&prepare.ballot, &top_vote) {
                            candidates.insert(prepare.ballot.clone());
                        }
                        if let Some(ref prepared) = prepare.prepared {
                            if are_ballots_less_and_compatible(prepared, &top_vote) {
                                candidates.insert(prepared.clone());
                            }
                        }
                        if let Some(ref prepared_prime) = prepare.prepared_prime {
                            if are_ballots_less_and_compatible(prepared_prime, &top_vote) {
                                candidates.insert(prepared_prime.clone());
                            }
                        }
                    }
                    proto::SCPStatement_pledges::SCP_ST_CONFIRM { confirm } => {
                        if are_ballots_compatible(&top_vote, &confirm.ballot) {
                            candidates.insert(top_vote.clone());
                            if confirm.n_prepared < top_vote.counter {
                                candidates.insert(proto::SCPBallot {
                                    counter: confirm.n_prepared,
                                    value: val.clone(),
                                });
                            }
                        }
                    }
                    proto::SCPStatement_pledges::SCP_ST_EXTERNALIZE { externalize } => {
                        if are_ballots_compatible(&top_vote, &externalize.commit) {
                            candidates.insert(top_vote.clone());
                        }
                    }
                    proto::SCPStatement_pledges::SCP_ST_NOMINATE { .. } => {
                        panic!("bug");
                    }
                }
            }
        }

        candidates
    }

    fn update_current_if_needed(&mut self, h: &proto::SCPBallot) -> bool {
        let should_update = match &self.ballot_state().current {
            None => true,
            Some(current) => compare_ballots(current, h) == Ordering::Less,
        };

        if should_update {
            self.bump_to_ballot(h.clone(), true);
            true
        } else {
            false
        }
    }

    fn has_prepared_ballot(ballot: &proto::SCPBallot, st: &proto::SCPStatement) -> bool {
        match &st.pledges {
            proto::SCPStatement_pledges::SCP_ST_PREPARE { prepare } => {
                let prepared_check = prepare
                    .prepared
                    .as_ref()
                    .map(|p| are_ballots_less_and_compatible(ballot, p))
                    .unwrap_or(false);

                let prepared_prime_check = prepare
                    .prepared_prime
                    .as_ref()
                    .map(|pp| are_ballots_less_and_compatible(ballot, pp))
                    .unwrap_or(false);

                prepared_check || prepared_prime_check
            }
            proto::SCPStatement_pledges::SCP_ST_CONFIRM { confirm } => {
                let prepared = proto::SCPBallot {
                    counter: confirm.n_prepared,
                    value: confirm.ballot.value.clone(),
                };
                are_ballots_less_and_compatible(ballot, &prepared)
            }
            proto::SCPStatement_pledges::SCP_ST_EXTERNALIZE { externalize } => {
                are_ballots_compatible(ballot, &externalize.commit)
            }
            proto::SCPStatement_pledges::SCP_ST_NOMINATE { .. } => {
                panic!("bug");
            }
        }
    }

    #[instrument(skip(voted, accepted))]
    fn federated_accept<F1, F2>(&self, voted: F1, accepted: F2) -> bool
    where
        F1: Fn(&proto::SCPStatement) -> bool,
        F2: Fn(&proto::SCPStatement) -> bool,
    {
        self.slot_proto()
            .federated_accept(voted, accepted, &self.ballot_state().latest_envelopes)
    }

    fn set_accept_prepared(&mut self, ballot: &proto::SCPBallot) -> bool {
        trace!(
            slot_index = self.slot_proto().index(),
            ballot = ?ballot,
            "BallotProtocol::setAcceptPrepared"
        );

        // Update our state
        let mut did_work = self.set_prepared(ballot.clone());

        // Check if we also need to clear 'c'
        if let (Some(_commit), Some(high)) =
            (&self.ballot_state().commit, &self.ballot_state().high)
        {
            let should_clear_commit =
                if let Some(prepared) = &self.ballot_state().prepared {
                    are_ballots_less_and_incompatible(high, prepared)
                } else {
                    false
                } || if let Some(prepared_prime) = &self.ballot_state().prepared_prime {
                    are_ballots_less_and_incompatible(high, prepared_prime)
                } else {
                    false
                };

            if should_clear_commit {
                assert_eq!(self.ballot_state().phase, Phase::Prepare);
                self.ballot_state_mut().commit = None;
                did_work = true;
            }
        }

        if did_work {
            self.consensus()
                .accepted_ballot_prepared(self.slot_proto().index(), ballot);
            self.emit_current_state_statement();
        }

        did_work
    }

    fn set_prepared(&mut self, ballot: proto::SCPBallot) -> bool {
        let mut did_work = false;

        // p and p' are the two highest prepared and incompatible ballots
        if let Some(ref prepared) = self.ballot_state().prepared {
            match compare_ballots(prepared, &ballot) {
                Ordering::Less => {
                    // as we're replacing p, we see if we should also replace p'
                    if !are_ballots_compatible(prepared, &ballot) {
                        self.ballot_state_mut().prepared_prime = Some(prepared.clone());
                    }
                    self.ballot_state_mut().prepared = Some(ballot);
                    did_work = true;
                }
                Ordering::Greater => {
                    // check if we should update only p', this happens
                    // either p' was NULL
                    // or p' gets replaced by ballot
                    //      (p' < ballot and ballot is incompatible with p)
                    // note, the later check is here out of paranoia as this function is
                    // not called with a value that would not allow us to make progress

                    let should_update_prime = match &self.ballot_state().prepared_prime {
                        None => true,
                        Some(prepared_prime) => {
                            compare_ballots(prepared_prime, &ballot) == Ordering::Less
                                && !are_ballots_compatible(prepared, &ballot)
                        }
                    };

                    if should_update_prime {
                        self.ballot_state_mut().prepared_prime = Some(ballot);
                        did_work = true;
                    }
                }
                Ordering::Equal => {
                    // Already have this ballot prepared, no work needed
                }
            }
        } else {
            self.ballot_state_mut().prepared = Some(ballot);
            did_work = true;
        }

        did_work
    }

    #[instrument(skip(voted))]
    fn federated_ratify<F>(&self, voted: F) -> bool
    where
        F: Fn(&proto::SCPStatement) -> bool,
    {
        self.slot_proto()
            .federated_ratify(voted, &self.ballot_state().latest_envelopes)
    }

    #[instrument]
    fn set_confirm_prepared(&mut self, new_c: &proto::SCPBallot, new_h: &proto::SCPBallot) -> bool {
        trace!(
            slot_index = self.slot_proto().index(),
            new_h = ?new_h,
            "ballot proto set_confirm_prepared"
        );

        let mut did_work = false;

        // remember newH's value
        self.ballot_state_mut().value_override = Some(new_h.value.clone());

        // we don't set c/h if we're not on a compatible ballot
        let should_update = match &self.ballot_state().current {
            None => true,
            Some(current) => are_ballots_compatible(current, new_h),
        };

        if should_update {
            if let Some(ref high) = self.ballot_state().high {
                if compare_ballots(new_h, high) == Ordering::Greater {
                    did_work = true;
                    self.ballot_state_mut().high = Some(new_h.clone());
                }
            } else {
                did_work = true;
                self.ballot_state_mut().high = Some(new_h.clone());
            }

            if new_c.counter != 0 {
                assert!(self.ballot_state().commit.is_none());
                self.ballot_state_mut().commit = Some(new_c.clone());
                did_work = true;
            }

            if did_work {
                self.consensus()
                    .confirmed_ballot_prepared(self.slot_proto().index(), new_h);
            }
        }

        // always perform step (8) with the computed value of h
        let current_updated = self.update_current_if_needed(new_h);
        did_work = current_updated || did_work;

        if did_work {
            self.emit_current_state_statement();
        }

        did_work
    }

    fn attempt_confirm_prepared(&mut self, hint: &proto::SCPStatement) -> bool {
        if self.ballot_state().phase != Phase::Prepare {
            return false;
        }

        // check if we could accept this ballot as prepared
        if self.ballot_state().prepared.is_none() {
            return false;
        }

        let candidates = self.get_prepare_candidates(hint);

        // See if we can accept any of the candidates, starting with the highest
        let mut new_h: Option<proto::SCPBallot> = None;
        let mut sorted_candidates: Vec<_> = candidates.into_iter().collect();
        sorted_candidates.sort_by(|a, b| compare_ballots(b, a)); // Sort in descending order

        // find newH
        let mut iter = sorted_candidates.iter();
        let mut cur = iter.next();
        while cur.is_some() {
            let ballot = cur.unwrap();

            // only consider it if we can potentially raise h
            if let Some(ref high) = self.ballot_state().high {
                if compare_ballots(high, ballot) != Ordering::Less {
                    break;
                }
            }

            let ratified = self.federated_ratify(|st: &proto::SCPStatement| -> bool {
                Self::has_prepared_ballot(ballot, st)
            });

            if ratified {
                new_h = Some(ballot.clone());
                break;
            }

            cur = iter.next();
        }

        if let Some(new_h_ballot) = new_h {
            let mut new_c: Option<&proto::SCPBallot> = None;

            // now, look for newC (left as None if no update)
            // step (3) from the paper
            let current_ballot = self.ballot_state().current.as_ref();

            let should_find_commit = self.ballot_state().commit.is_none()
                && (self
                    .ballot_state()
                    .prepared
                    .as_ref()
                    .map(|p| !are_ballots_less_and_incompatible(&new_h_ballot, p))
                    .unwrap_or(true))
                && (self
                    .ballot_state()
                    .prepared_prime
                    .as_ref()
                    .map(|pp| !are_ballots_less_and_incompatible(&new_h_ballot, pp))
                    .unwrap_or(true));

            if should_find_commit {
                // continue where we left off (cur is at newH at this point)
                while cur.is_some() {
                    let ballot = cur.unwrap();

                    if let Some(current) = current_ballot {
                        if compare_ballots(ballot, current) == Ordering::Less {
                            break;
                        }
                    }

                    // c and h must be compatible
                    if !are_ballots_less_and_compatible(ballot, &new_h_ballot) {
                        continue;
                    }

                    let ratified = self.federated_ratify(|st: &proto::SCPStatement| -> bool {
                        Self::has_prepared_ballot(ballot, st)
                    });

                    if ratified {
                        new_c = Some(ballot);
                    } else {
                        break;
                    }

                    cur = iter.next();
                }
            }

            return self.set_confirm_prepared(new_c.unwrap(), &new_h_ballot);
        }

        false
    }

    #[instrument]
    fn check_heard_from_quorum(&mut self) {
        // this method is safe to call regardless of the transitions of the other
        // nodes on the network:
        // we guarantee that other nodes can only transition to higher counters
        // (messages are ignored upstream)
        // therefore the local node will not flip flop between "seen" and "not seen"
        // for a given counter on the local node
        if let Some(current_ballot) = &self.ballot_state().current.clone() {
            let is_quorum = LocalProto::is_quorum(
                self.slot_proto().local_proto().get_qset(),
                &self.ballot_state().latest_envelopes,
                |st: &proto::SCPStatement| -> Option<proto::SCPQuorumSet> {
                    self.slot_proto().get_quorum_set_from_statement(st)
                },
                |st: &proto::SCPStatement| -> bool {
                    match &st.pledges {
                        proto::SCPStatement_pledges::SCP_ST_PREPARE { prepare } => {
                            current_ballot.counter <= prepare.ballot.counter
                        }
                        _ => true,
                    }
                },
            );

            if is_quorum {
                let old_hq = self.ballot_state().heard_from_quorum;
                self.ballot_state_mut().heard_from_quorum = true;

                if !old_hq {
                    // if we transition from not heard -> heard, we start the timer
                    self.consensus()
                        .ballot_did_hear_from_quorum(self.slot_proto().index(), current_ballot);
                    if self.ballot_state().phase != Phase::Externalize {
                        self.start_timer();
                    }
                }

                if self.ballot_state().phase == Phase::Externalize {
                    self.stop_timer();
                }
            } else {
                self.ballot_state_mut().heard_from_quorum = false;
                self.stop_timer();
            }
        }
    }

    fn check_invariants(&self) {
        match self.ballot_state().phase {
            Phase::Prepare => {}
            Phase::Confirm | Phase::Externalize => {
                assert!(self.ballot_state().current.is_some());
                assert!(self.ballot_state().prepared.is_some());
                assert!(self.ballot_state().commit.is_some());
                assert!(self.ballot_state().high.is_some());
            }
            Phase::Num => {
                panic!("bug");
            }
        }

        if let Some(current) = &self.ballot_state().current {
            assert!(current.counter != 0);
        }

        if let (Some(prepared_prime), Some(prepared)) = (
            &self.ballot_state().prepared_prime,
            &self.ballot_state().prepared,
        ) {
            assert!(are_ballots_less_and_incompatible(prepared_prime, prepared));
        }

        if let Some(high) = &self.ballot_state().high {
            assert!(self.ballot_state().current.is_some(),);
            assert!(are_ballots_less_and_compatible(
                high,
                self.ballot_state().current.as_ref().unwrap()
            ),);
        }

        if let Some(commit) = &self.ballot_state().commit {
            assert!(self.ballot_state().current.is_some());
            assert!(self.ballot_state().high.is_some());

            let high = self.ballot_state().high.as_ref().unwrap();
            let current = self.ballot_state().current.as_ref().unwrap();

            assert!(are_ballots_less_and_compatible(commit, high));
            assert!(are_ballots_less_and_compatible(high, current));
        }
    }

    #[instrument]
    fn attempt_accept_prepared(&mut self, hint: &proto::SCPStatement) -> bool {
        if self.ballot_state().phase != Phase::Prepare
            && self.ballot_state().phase != Phase::Confirm
        {
            return false;
        }

        let candidates = self.get_prepare_candidates(hint);

        // see if we can accept any of the candidates, starting with the highest
        let mut sorted_candidates: Vec<_> = candidates.into_iter().collect();
        sorted_candidates.sort_by(|a, b| compare_ballots(b, a)); // Sort in descending order (reverse)

        for ballot in sorted_candidates {
            if self.ballot_state().phase == Phase::Confirm {
                // only consider the ballot if it may help us increase
                // p (note: at this point, p ~ c)
                if !are_ballots_less_and_compatible(
                    &self.ballot_state().prepared.as_ref().unwrap(),
                    &ballot,
                ) {
                    continue;
                }
                assert!(are_ballots_compatible(
                    &self.ballot_state().commit.as_ref().unwrap(),
                    &ballot
                ));
            }

            // if we already prepared this ballot, don't bother checking again

            // if ballot <= p' ballot is neither a candidate for p nor p'
            if let Some(ref prepared_prime) = self.ballot_state().prepared_prime {
                if compare_ballots(&ballot, prepared_prime) != Ordering::Greater {
                    continue;
                }
            }

            if let Some(ref prepared) = self.ballot_state().prepared {
                // if ballot is already covered by p, skip
                if are_ballots_less_and_compatible(&ballot, prepared) {
                    continue;
                }
                // otherwise, there is a chance it increases p'
            }

            let accepted = self.federated_accept(
                // checks if any node is voting for this ballot
                |st: &proto::SCPStatement| -> bool {
                    match &st.pledges {
                        proto::SCPStatement_pledges::SCP_ST_PREPARE { prepare } => {
                            are_ballots_less_and_compatible(&ballot, &prepare.ballot)
                        }
                        proto::SCPStatement_pledges::SCP_ST_CONFIRM { confirm } => {
                            are_ballots_compatible(&ballot, &confirm.ballot)
                        }
                        proto::SCPStatement_pledges::SCP_ST_EXTERNALIZE { externalize } => {
                            are_ballots_compatible(&ballot, &externalize.commit)
                        }
                        _ => panic!("bug"),
                    }
                },
                |st: &proto::SCPStatement| -> bool { Self::has_prepared_ballot(&ballot, st) },
            );

            if accepted {
                return self.set_accept_prepared(&ballot);
            }
        }

        false
    }

    fn commit_predicate(
        ballot: &proto::SCPBallot,
        check: &Interval,
        st: &proto::SCPStatement,
    ) -> bool {
        match &st.pledges {
            proto::SCPStatement_pledges::SCP_ST_PREPARE { .. } => false,
            proto::SCPStatement_pledges::SCP_ST_CONFIRM { confirm } => {
                if are_ballots_compatible(ballot, &confirm.ballot) {
                    confirm.n_commit <= check.lo && check.hi <= confirm.n_h
                } else {
                    false
                }
            }
            proto::SCPStatement_pledges::SCP_ST_EXTERNALIZE { externalize } => {
                if are_ballots_compatible(ballot, &externalize.commit) {
                    externalize.commit.counter <= check.lo
                } else {
                    false
                }
            }
            _ => panic!("bug"),
        }
    }

    /// helper function to find a contiguous range 'candidate' that satisfies the
    /// predicate. updates 'candidate' (or leave it unchanged)
    fn find_extended_interval<F>(
        candidate: &mut Interval,
        boundaries: &HashSet<proto::SCPCount>,
        pred: F,
    ) where
        F: Fn(&Interval) -> bool,
    {
        // collect boundaries into a vector and sort, then iterate from the top
        let mut sorted_boundaries: Vec<proto::SCPCount> = boundaries.iter().copied().collect();
        sorted_boundaries.sort();

        for &b in sorted_boundaries.iter().rev() {
            let cur = if candidate.lo == 0 {
                // first, find the high bound
                Interval { lo: b, hi: b }
            } else if b > candidate.hi {
                // invalid
                continue;
            } else {
                Interval {
                    lo: b,
                    hi: candidate.hi,
                }
            };

            if pred(&cur) {
                *candidate = cur;
            } else if candidate.lo != 0 {
                // could not extend further
                break;
            }
        }
    }

    /// constructs the set of counters representing the
    /// commit ballots compatible with the ballot
    fn get_commit_boundaries_from_statements(
        &self,
        ballot: &proto::SCPBallot,
    ) -> HashSet<proto::SCPCount> {
        let mut res = HashSet::new();

        for envelope in self.ballot_state().latest_envelopes.values() {
            match &envelope.statement.pledges {
                proto::SCPStatement_pledges::SCP_ST_PREPARE { prepare } => {
                    if are_ballots_compatible(ballot, &prepare.ballot) {
                        if prepare.n_c != 0 {
                            res.insert(prepare.n_c);
                            res.insert(prepare.n_h);
                        }
                    }
                }
                proto::SCPStatement_pledges::SCP_ST_CONFIRM { confirm } => {
                    if are_ballots_compatible(ballot, &confirm.ballot) {
                        res.insert(confirm.n_commit);
                        res.insert(confirm.n_h);
                    }
                }
                proto::SCPStatement_pledges::SCP_ST_EXTERNALIZE { externalize } => {
                    if are_ballots_compatible(ballot, &externalize.commit) {
                        res.insert(externalize.commit.counter);
                        res.insert(externalize.n_h);
                        res.insert(u32::MAX);
                    }
                }
                _ => panic!("bug"),
            }
        }

        res
    }

    #[instrument]
    fn set_accept_commit(&mut self, c: &proto::SCPBallot, h: &proto::SCPBallot) -> bool {
        trace!(
            slot_index = self.slot_proto().index(),
            c = ?c,
            h = ?h,
            "ballot proto set_accept_commit"
        );

        let mut did_work = false;

        // remember h's value
        self.ballot_state_mut().value_override = Some(h.value.clone());

        let high_changed = match &self.ballot_state().high {
            None => true,
            Some(current_high) => compare_ballots(current_high, h) != Ordering::Equal,
        };

        let commit_changed = match &self.ballot_state().commit {
            None => true,
            Some(current_commit) => compare_ballots(current_commit, c) != Ordering::Equal,
        };

        if high_changed || commit_changed {
            self.ballot_state_mut().commit = Some(c.clone());
            self.ballot_state_mut().high = Some(h.clone());
            did_work = true;
        }

        if self.ballot_state().phase == Phase::Prepare {
            self.ballot_state_mut().phase = Phase::Confirm;

            if let Some(current) = &self.ballot_state().current {
                if !are_ballots_less_and_compatible(h, current) {
                    self.bump_to_ballot(h.clone(), false);
                }
            }

            self.ballot_state_mut().prepared_prime = None;
            did_work = true;
        }

        if did_work {
            self.update_current_if_needed(&self.ballot_state().high.as_ref().unwrap().clone());
            self.consensus()
                .accepted_commit(self.slot_proto().index(), h);
            self.emit_current_state_statement();
        }

        did_work
    }

    #[instrument]
    fn attempt_accept_commit(&mut self, hint: &proto::SCPStatement) -> bool {
        if self.ballot_state().phase != Phase::Prepare
            && self.ballot_state().phase != Phase::Confirm
        {
            return false;
        }

        // extracts value from hint
        // note: ballot.counter is only used for logging purpose as we're looking at
        // possible value to commit
        let ballot = match &hint.pledges {
            proto::SCPStatement_pledges::SCP_ST_PREPARE { prepare } => {
                if prepare.n_c != 0 {
                    proto::SCPBallot {
                        counter: prepare.n_h,
                        value: prepare.ballot.value.clone(),
                    }
                } else {
                    return false;
                }
            }
            proto::SCPStatement_pledges::SCP_ST_CONFIRM { confirm } => proto::SCPBallot {
                counter: confirm.n_h,
                value: confirm.ballot.value.clone(),
            },
            proto::SCPStatement_pledges::SCP_ST_EXTERNALIZE { externalize } => proto::SCPBallot {
                counter: externalize.n_h,
                value: externalize.commit.value.clone(),
            },
            _ => panic!("bug"),
        };

        if self.ballot_state().phase == Phase::Confirm {
            if !are_ballots_compatible(&ballot, self.ballot_state().high.as_ref().unwrap()) {
                return false;
            }
        }

        let pred = |cur: &Interval| -> bool {
            self.federated_accept(
                |st: &proto::SCPStatement| -> bool {
                    match &st.pledges {
                        proto::SCPStatement_pledges::SCP_ST_PREPARE { prepare } => {
                            if are_ballots_compatible(&ballot, &prepare.ballot) {
                                if prepare.n_c != 0 {
                                    prepare.n_c <= cur.lo && cur.hi <= prepare.n_h
                                } else {
                                    false
                                }
                            } else {
                                false
                            }
                        }
                        proto::SCPStatement_pledges::SCP_ST_CONFIRM { confirm } => {
                            if are_ballots_compatible(&ballot, &confirm.ballot) {
                                confirm.n_commit <= cur.lo
                            } else {
                                false
                            }
                        }
                        proto::SCPStatement_pledges::SCP_ST_EXTERNALIZE { externalize } => {
                            if are_ballots_compatible(&ballot, &externalize.commit) {
                                externalize.commit.counter <= cur.lo
                            } else {
                                false
                            }
                        }
                        _ => panic!("bug"),
                    }
                },
                |st: &proto::SCPStatement| -> bool { Self::commit_predicate(&ballot, cur, st) },
            )
        };

        // build the boundaries to scan
        let boundaries = self.get_commit_boundaries_from_statements(&ballot);

        if boundaries.is_empty() {
            return false;
        }

        // now, look for the high interval
        let mut candidate = Interval { lo: 0, hi: 0 };
        Self::find_extended_interval(&mut candidate, &boundaries, pred);

        if candidate.lo != 0 {
            if self.ballot_state().phase != Phase::Confirm
                || candidate.hi > self.ballot_state().high.as_ref().unwrap().counter
            {
                let c = proto::SCPBallot {
                    counter: candidate.lo,
                    value: ballot.value.clone(),
                };
                let h = proto::SCPBallot {
                    counter: candidate.hi,
                    value: ballot.value.clone(),
                };
                return self.set_accept_commit(&c, &h);
            }
        }

        false
    }

    #[instrument]
    fn attempt_bump(&mut self) -> bool {
        if self.ballot_state().phase == Phase::Prepare
            || self.ballot_state().phase == Phase::Confirm
        {
            // First check to see if this condition applies at all. If there
            // is no v-blocking set ahead of the local node, there's nothing
            // to do, return early.
            let local_counter = match &self.ballot_state().current {
                Some(current) => current.counter,
                None => 0,
            };

            if !has_v_blocking_subset_strictly_ahead_of(
                &self.slot_proto().local_proto(),
                &self.ballot_state().latest_envelopes,
                local_counter,
            ) {
                return false;
            }

            // Collect all possible counters we might need to advance to.
            let mut all_counters = HashSet::new();
            for envelope in self.ballot_state().latest_envelopes.values() {
                let c = statement_ballot_counter(&envelope.statement);
                if c > local_counter {
                    all_counters.insert(c);
                }
            }

            let mut all_counters_sorted: Vec<proto::SCPCount> = all_counters.into_iter().collect();
            all_counters_sorted.sort();

            // If we got to here, implicitly there _was_ a v-blocking subset
            // with counters above the local counter; we just need to find a
            // minimal n at which that's no longer true. So check them in
            // order, starting from the smallest.
            for n in all_counters_sorted {
                if !has_v_blocking_subset_strictly_ahead_of(
                    &self.slot_proto().local_proto(),
                    &self.ballot_state().latest_envelopes,
                    n,
                ) {
                    // Move to n.
                    return self.abandon_ballot(n);
                }
            }
        }
        false
    }

    #[instrument]
    fn attempt_confirm_commit(&mut self, hint: &proto::SCPStatement) -> bool {
        if self.ballot_state().phase != Phase::Confirm {
            return false;
        }

        if self.ballot_state().high.is_none() || self.ballot_state().commit.is_none() {
            return false;
        }

        // extracts value from hint
        // note: ballot.counter is only used for logging purpose
        let ballot = match &hint.pledges {
            proto::SCPStatement_pledges::SCP_ST_PREPARE { .. } => {
                return false;
            }
            proto::SCPStatement_pledges::SCP_ST_CONFIRM { confirm } => proto::SCPBallot {
                counter: confirm.n_h,
                value: confirm.ballot.value.clone(),
            },
            proto::SCPStatement_pledges::SCP_ST_EXTERNALIZE { externalize } => proto::SCPBallot {
                counter: externalize.n_h,
                value: externalize.commit.value.clone(),
            },
            _ => panic!("bug"),
        };

        if !are_ballots_compatible(&ballot, self.ballot_state().commit.as_ref().unwrap()) {
            return false;
        }

        let boundaries = self.get_commit_boundaries_from_statements(&ballot);
        let mut candidate = Interval { lo: 0, hi: 0 };

        let pred = |cur: &Interval| -> bool {
            self.federated_ratify(|st: &proto::SCPStatement| -> bool {
                Self::commit_predicate(&ballot, cur, st)
            })
        };

        Self::find_extended_interval(&mut candidate, &boundaries, pred);

        if candidate.lo != 0 {
            let c = proto::SCPBallot {
                counter: candidate.lo,
                value: ballot.value.clone(),
            };
            let h = proto::SCPBallot {
                counter: candidate.hi,
                value: ballot.value.clone(),
            };
            return self.set_confirm_commit(&c, &h);
        }

        false
    }

    #[instrument]
    fn set_confirm_commit(&mut self, c: &proto::SCPBallot, h: &proto::SCPBallot) -> bool {
        trace!(
            slot_index = self.slot_proto().index(),
            c = ?c,
            h = ?h,
            "ballot proto set_confirm_commit"
        );

        self.ballot_state_mut().commit = Some(c.clone());
        self.ballot_state_mut().high = Some(h.clone());
        self.update_current_if_needed(h);

        self.ballot_state_mut().phase = Phase::Externalize;

        self.emit_current_state_statement();

        self.slot_proto_mut().stop_nomination();

        self.consensus()
            .value_externalized(self.slot_proto().index(), &c.value);

        true
    }

    // returns the hash of the QuorumSet that should be downloaded
    // with the statement.
    // note: the companion hash for an EXTERNALIZE statement does
    // not match the hash of the QSet, but the hash of commitQuorumSetHash
    fn get_companion_quorum_set_hash_from_statement(st: &proto::SCPStatement) -> proto::SCPHash {
        match &st.pledges {
            proto::SCPStatement_pledges::SCP_ST_PREPARE { prepare } => {
                prepare.quorum_set_hash.clone()
            }
            proto::SCPStatement_pledges::SCP_ST_CONFIRM { confirm } => {
                confirm.quorum_set_hash.clone()
            }
            proto::SCPStatement_pledges::SCP_ST_EXTERNALIZE { externalize } => {
                externalize.commit_quorum_set_hash.clone()
            }
            _ => panic!("bug"),
        }
    }

    // helper function to retrieve b for PREPARE, P for CONFIRM or
    // c for EXTERNALIZE messages
    fn get_working_ballot(st: &proto::SCPStatement) -> proto::SCPBallot {
        match &st.pledges {
            proto::SCPStatement_pledges::SCP_ST_PREPARE { prepare } => prepare.ballot.clone(),
            proto::SCPStatement_pledges::SCP_ST_CONFIRM { confirm } => proto::SCPBallot {
                counter: confirm.n_commit,
                value: confirm.ballot.value.clone(),
            },
            proto::SCPStatement_pledges::SCP_ST_EXTERNALIZE { externalize } => {
                externalize.commit.clone()
            }
            _ => panic!("bug"),
        }
    }

    #[instrument]
    pub fn set_state_from_envelope(&mut self, env: &proto::SCPEnvelope) {
        // cannot set state after starting ballot protocol
        assert!(self.ballot_state().current.is_none());

        self.record_envelope(env);

        self.ballot_state_mut().last_envelope_gen = Some(env.clone());
        self.ballot_state_mut().last_envelope_emit = Some(env.clone());

        match &env.statement.pledges {
            proto::SCPStatement_pledges::SCP_ST_PREPARE { prepare } => {
                let b = &prepare.ballot;
                self.bump_to_ballot(b.clone(), true);

                if let Some(prepared) = &prepare.prepared {
                    self.ballot_state_mut().prepared = Some(prepared.clone());
                }

                if let Some(prepared_prime) = &prepare.prepared_prime {
                    self.ballot_state_mut().prepared_prime = Some(prepared_prime.clone());
                }

                if prepare.n_h != 0 {
                    self.ballot_state_mut().high = Some(proto::SCPBallot {
                        counter: prepare.n_h,
                        value: b.value.clone(),
                    });
                }

                if prepare.n_c != 0 {
                    self.ballot_state_mut().commit = Some(proto::SCPBallot {
                        counter: prepare.n_c,
                        value: b.value.clone(),
                    });
                }

                self.ballot_state_mut().phase = Phase::Prepare;
            }
            proto::SCPStatement_pledges::SCP_ST_CONFIRM { confirm } => {
                let v = &confirm.ballot.value;
                self.bump_to_ballot(confirm.ballot.clone(), true);

                self.ballot_state_mut().prepared = Some(proto::SCPBallot {
                    counter: confirm.n_prepared,
                    value: v.clone(),
                });

                self.ballot_state_mut().high = Some(proto::SCPBallot {
                    counter: confirm.n_h,
                    value: v.clone(),
                });

                self.ballot_state_mut().commit = Some(proto::SCPBallot {
                    counter: confirm.n_commit,
                    value: v.clone(),
                });

                self.ballot_state_mut().phase = Phase::Confirm;
            }
            proto::SCPStatement_pledges::SCP_ST_EXTERNALIZE { externalize } => {
                let v = &externalize.commit.value;
                self.bump_to_ballot(
                    proto::SCPBallot {
                        counter: u32::MAX,
                        value: v.clone(),
                    },
                    true,
                );

                self.ballot_state_mut().prepared = Some(proto::SCPBallot {
                    counter: u32::MAX,
                    value: v.clone(),
                });

                self.ballot_state_mut().high = Some(proto::SCPBallot {
                    counter: externalize.n_h,
                    value: v.clone(),
                });

                self.ballot_state_mut().commit = Some(externalize.commit.clone());

                self.ballot_state_mut().phase = Phase::Externalize;
            }
            _ => panic!("bug"),
        }
    }

    pub fn process_current_state<F>(&self, f: &mut F, force_self: bool) -> bool
    where
        F: FnMut(&proto::SCPEnvelope) -> bool,
    {
        for (node_id, envelope) in &self.ballot_state().latest_envelopes {
            // only return messages for self if the slot is fully validated
            if force_self
                || node_id != self.slot_proto().local_proto().get_node_id()
                || self.slot_proto().is_fully_validated()
            {
                if !f(envelope) {
                    return false;
                }
            }
        }
        true
    }

    pub fn get_latest_message(&self, id: &proto::SCPNodeID) -> Option<proto::SCPEnvelope> {
        self.ballot_state().latest_envelopes.get(id).cloned()
    }

    pub fn get_externalizing_state(&self) -> Vec<proto::SCPEnvelope> {
        let mut res = Vec::new();

        if self.ballot_state().phase == Phase::Externalize {
            res.reserve(self.ballot_state().latest_envelopes.len());

            for (node_id, envelope) in &self.ballot_state().latest_envelopes {
                if node_id != self.slot_proto().local_proto().get_node_id() {
                    // good approximation: statements with the value that externalized
                    // we could filter more using mConfirmedPrepared as well
                    if are_ballots_compatible(
                        &Self::get_working_ballot(&envelope.statement),
                        self.ballot_state().commit.as_ref().unwrap(),
                    ) {
                        res.push(envelope.clone());
                    }
                } else if self.slot_proto().is_fully_validated() {
                    // only return messages for self if the slot is fully validated
                    res.push(envelope.clone());
                }
            }
        }

        res
    }

    #[instrument]
    fn validate_values(&self, st: &proto::SCPStatement) -> ValidationLevel {
        let values = Self::get_statement_values(st);

        if values.is_empty() {
            // This shouldn't happen
            return ValidationLevel::Invalid;
        }

        let mut res = ValidationLevel::FullyValid;
        for value in values {
            if res > ValidationLevel::Invalid {
                let validation_result = self
                    .consensus()
                    .validate_ballot_value(self.slot_proto().index(), &value);
                res = std::cmp::min(validation_result, res);
            }
        }

        res
    }

    fn get_state(&self, n: &proto::SCPNodeID, self_already_moved_on: bool) -> QuorumInfoNodeState {
        let mut state = QuorumInfoNodeState::Agree;

        if n == self.slot_proto().local_proto().get_node_id() {
            // always mark myself as AGREE.
            return state;
        }

        let envelope_opt = self.ballot_state().latest_envelopes.get(n);

        if envelope_opt.is_none() {
            if self.ballot_state().timer_exp_count >= NUM_TIMEOUTS_THRESHOLD_FOR_REPORTING
                || self_already_moved_on
            {
                state = QuorumInfoNodeState::Missing;
            } else {
                // It's too soon to start calling this node MISSING.
                state = QuorumInfoNodeState::NoInfo;
            }
        } else if let Some(last_envelope_emit) = &self.ballot_state().last_envelope_emit {
            let envelope = envelope_opt.unwrap();
            let st = &envelope.statement;
            let externalized = matches!(
                st.pledges,
                proto::SCPStatement_pledges::SCP_ST_EXTERNALIZE { .. }
            );

            let confirmed_commit = match &st.pledges {
                proto::SCPStatement_pledges::SCP_ST_CONFIRM { confirm } => {
                    confirm.ballot.counter == u32::MAX
                }
                _ => false,
            };

            if self.ballot_state().phase == Phase::Externalize
                && (!externalized || !confirmed_commit)
                && self_already_moved_on
            {
                // We have already externalized and moved onto the next slot.
                // However, this node hasn't externalized yet.
                state = QuorumInfoNodeState::Delayed;
            }

            let self_accepted_confirm = self.ballot_state().phase == Phase::Confirm
                || self.ballot_state().phase == Phase::Externalize;

            let other_accepted_confirm = matches!(
                st.pledges,
                proto::SCPStatement_pledges::SCP_ST_CONFIRM { .. }
                    | proto::SCPStatement_pledges::SCP_ST_EXTERNALIZE { .. }
            );

            let self_st = &last_envelope_emit.statement;

            if self_accepted_confirm
                && other_accepted_confirm
                && !are_ballots_compatible(
                    &Self::get_working_ballot(st),
                    &Self::get_working_ballot(self_st),
                )
            {
                // n has accepted to commit a different value than mine!
                // Even if this node has been marked something else,
                // we will overwrite it since this is bad.
                state = QuorumInfoNodeState::Disagree;
            }
        }

        state
    }

    fn get_json_quorum_info(
        &self,
        id: &proto::SCPNodeID,
        summary: bool,
        full_keys: bool,
    ) -> serde_json::Value {
        let mut ret = serde_json::json!({});

        // find the state of the node `id`
        let mut b = proto::SCPBallot {
            counter: 0,
            value: proto::SCPValue::default(),
        };
        let mut q_set_hash = proto::SCPHash::default();

        let envelope_opt = self.ballot_state().latest_envelopes.get(id);
        if envelope_opt.is_none() {
            ret["phase"] = serde_json::Value::String("unknown".to_string());
            if id == self.slot_proto().local_proto().get_node_id() {
                q_set_hash = *self.slot_proto().local_proto().get_qset_hash();
            }
        } else {
            let envelope = envelope_opt.unwrap();
            let st = &envelope.statement;

            match &st.pledges {
                proto::SCPStatement_pledges::SCP_ST_PREPARE { prepare } => {
                    ret["phase"] = serde_json::Value::String("PREPARE".to_string());
                    b = prepare.ballot.clone();
                }
                proto::SCPStatement_pledges::SCP_ST_CONFIRM { confirm } => {
                    ret["phase"] = serde_json::Value::String("CONFIRM".to_string());
                    b = confirm.ballot.clone();
                }
                proto::SCPStatement_pledges::SCP_ST_EXTERNALIZE { externalize } => {
                    ret["phase"] = serde_json::Value::String("EXTERNALIZE".to_string());
                    b = externalize.commit.clone();
                }
                _ => panic!("bug"),
            }

            // use the companion set here even for externalize to capture
            // the view of the quorum set during consensus
            q_set_hash = Self::get_companion_quorum_set_hash_from_statement(st);
        }

        let q_set = self.driver().get_qset(&q_set_hash);
        if q_set.is_none() {
            ret["phase"] = serde_json::Value::String("expired".to_string());
            return ret;
        }

        let q_set = q_set.unwrap();
        let local_proto = self.slot_proto().local_proto();
        let f = local_proto.find_closest_v_blocking_envelopes(
            &q_set,
            &self.ballot_state().latest_envelopes,
            |st: &proto::SCPStatement| -> bool {
                are_ballots_compatible(&Self::get_working_ballot(st), &b)
            },
            Some(id),
        );

        ret["fail_at"] = serde_json::Value::Number(serde_json::Number::from(f.len()));

        if !summary {
            let mut f_ex = serde_json::json!([]);
            for n in f {
                f_ex.as_array_mut().unwrap().push(serde_json::Value::String(
                    self.driver().to_str_key(&n, full_keys),
                ));
            }
            ret["fail_with"] = f_ex;
            ret["value"] = self.slot_proto().local_proto().to_json(&q_set, full_keys);
        }

        ret["hash"] = serde_json::Value::String(hex_abbrev(&q_set_hash));

        ret
    }

    // attempts to make progress using the latest statement as a hint
    // calls into the various attempt* methods, emits message
    // to make progress
    #[instrument]
    fn advance_slot(&mut self, hint: &proto::SCPStatement) {
        const MAX_ADVANCE_SLOT_RECURSION: i64 = 100;

        self.ballot_state_mut().msg_level += 1;
        trace!(
            msg_level = self.ballot_state().msg_level,
            local_state = ?self.get_local_state(),
            "ballot proto advance_slot"
        );

        if self.ballot_state().msg_level >= MAX_ADVANCE_SLOT_RECURSION {
            panic!("maximum number of transitions reached in advance_slot");
        }

        // attempt* methods will queue up messages, causing advance_slot to be
        // called recursively

        // done in order so that we follow the steps from the white paper in
        // order allowing the state to be updated properly

        let mut did_work = false;

        did_work = self.attempt_accept_prepared(hint) || did_work;

        did_work = self.attempt_confirm_prepared(hint) || did_work;

        did_work = self.attempt_accept_commit(hint) || did_work;

        did_work = self.attempt_confirm_commit(hint) || did_work;

        // only bump after we're done with everything else
        if self.ballot_state().msg_level == 1 {
            let mut did_bump = false;
            loop {
                // attempt_bump may invoke advance_slot recursively
                did_bump = self.attempt_bump();
                did_work = did_bump || did_work;
                if !did_bump {
                    break;
                }
            }

            self.check_heard_from_quorum();
        }

        trace!(
            msg_level = self.ballot_state().msg_level,
            local_state = ?self.get_local_state(),
            "ballot proto advance_slot exiting"
        );

        self.ballot_state_mut().msg_level -= 1;

        if did_work {
            self.send_latest_envelope();
        }
    }

    fn get_local_state(&self) -> String {
        let state = LocalState {
            slot_index: self.slot_proto().index(),
            ballot: self.ballot_state(),
        };
        format!("{:?}", state)
    }

    pub fn get_json_info(&self) -> serde_json::Value {
        json!({
           "heard": self.ballot_state().heard_from_quorum,
           "ballot": self.ballot_to_str(self.ballot_state().current.as_ref()),
           "phase": self.ballot_state().phase.to_string(),
           "state": self.get_local_state(),
        })
    }

    pub fn ballot_to_str(&self, b: Option<&proto::SCPBallot>) -> String {
        match b {
            Some(b) => format!(
                "<{},{}>",
                b.counter,
                self.driver().get_value_string(&b.value),
            ),
            None => "<,>".to_string(),
        }
    }

    pub fn get_last_message_send(&self) -> Option<proto::SCPEnvelope> {
        self.ballot_state().last_envelope_emit.clone()
    }
}


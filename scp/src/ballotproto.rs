use crate::*;
use std::collections::HashMap;

/// BallotProtocol
pub struct BallotProto<'a> {
    slot: &'a SlotProto<'a>,

    heard_from_quorum: bool,

    current: Option<proto::SCPBallot>,        // b
    prepared: Option<proto::SCPBallot>,       // p
    prepared_prime: Option<proto::SCPBallot>, // p'
    high: Option<proto::SCPBallot>,           // h
    commit: Option<proto::SCPBallot>,         // c
    value: Option<proto::SCPBallot>,          // z
    latest_envelopes: HashMap<proto::SCPNodeID, proto::SCPEnvelope>, // M
    phase: SCPPhase,                          // phi

    msg_level: i64,       // number of messages triggered in one run
    timer_exp_count: i64, // number of times the timer has expired; used for the quorum endpoint

    last_envelope_gen: Option<proto::SCPEnvelope>, // last envelope generated by this node
    last_envelope_emit: Option<proto::SCPEnvelope>, // last envelope emitted by this node
}

impl<'a> BallotProto<'a> {
    pub fn new(slot: &'a SlotProto<'a>) -> Self {
        BallotProto {
            slot,
            heard_from_quorum: false,
            current: None,
            prepared: None,
            prepared_prime: None,
            high: None,
            commit: None,
            value: None,
            latest_envelopes: HashMap::new(),
            phase: SCPPhase::Prepare,
            msg_level: 0,
            timer_exp_count: 0,
            last_envelope_gen: None,
            last_envelope_emit: None,
        }
    }

    pub fn is_newer_statement(node_id: &proto::SCPNodeID, st: &proto::SCPStatement) -> bool {
        panic!("XXX")
    }
}
